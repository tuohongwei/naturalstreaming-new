"""Publish a generated diagnostic tone theme for the frontend test account.
This is explicitly a synthetic test signal, not either supplied music theme.
Uses private owner and frontend files under .local. Never prints secrets.
"""
import sys,json,io,wave,math,struct,hashlib
from pathlib import Path
sys.path.insert(0,str(Path(__file__).parent))
from upload_theme import request

def main():
 root=Path(__file__).resolve().parent.parent;c=json.loads((root/'.local/owner-access.json').read_text());f=json.loads((root/'.local/frontend-access.json').read_text())
 tracks=[];files=[];theme='integration-tone-demo'
 for i in range(1,11):
  buf=io.BytesIO()
  with wave.open(buf,'wb') as w:
   w.setparams((1,2,16000,0,'NONE','not compressed'))
   w.writeframes(b''.join(struct.pack('<h',int(800*math.sin(n*2*math.pi*(180+i*20)/16000))) for n in range(48000)))
  data=buf.getvalue();sha=hashlib.sha256(data).hexdigest();request(c['media'],'/v1/uploads/'+sha,'PUT',data,c['uploadToken'])
  clips=[f'media/{i}a.wav',f'media/{i}b.wav']
  for p in clips:files.append({'path':p,'sha256':sha,'bytes':len(data),'channels':1,'codec':'pcm_s16le','container':'wav'})
  tracks.append({'id':str(i),'label':f'合成测试音 {i}','description':f'{180+i*20} Hz 低幅度正弦波，仅供混音和下载联调，非自然声音素材。','clips':clips,'gain':0.08,'overlap_seconds':1,'channels':1,'spatial_role':'point_source','diffuse':False,'map_position':[0,-1]})
 presets=[]
 for id,label,values in [('balanced','均衡',[0.08]*10),('quiet','轻声',[0.045]*10),('first-half','前半组突出',[0.11]*5+[0.025]*5),('second-half','后半组突出',[0.025]*5+[0.11]*5),('slow-variation','缓慢变化',[0.08]*10)]:
  presets.append({'id':id,'label':label,'gains':{str(i+1):v for i,v in enumerate(values)},'transition_seconds':2,'animation':{'enabled':True,'mode':'soft','interval_seconds':30,'min_gain_multiplier':0.75,'max_gain_multiplier':1.15} if id=='slow-variation' else {'enabled':False}})
 scene={'id':theme,'schema_version':1,'name':'联调测试音（非音乐）','description':'10轨合成信号，用于下载、混音和离线流程验收，请低音量播放。','tracks':tracks,'default_preset':'balanced','presets':presets}
 draft={'scene':scene,'manifest':{'theme_id':theme,'schema_version':1,'files':files},'license':{'source':'Generated by ops/provision_demo.py, mathematical sine waves','license':'CC0','reviewed':True}}
 p=f'/v1/admin/themes/{theme}/versions/1'
 request(c['admin'],p,'PUT',draft,c['uploadToken']);v=request(c['admin'],p+'/validate','POST',{},c['uploadToken']);assert v['valid'],v
 request(c['admin'],p+'/publish','POST',{},c['publisherToken'])
 for id in [theme,'forest-in-the-morning']:
  request(c['admin'],f"/v1/admin/accounts/{f['accountId']}/themes/{id}",'PUT',{'allowed':True},c['publisherToken'])
 print('Published diagnostic demo and granted test account; supplied real themes remain draft pending annotation/license review')

if __name__=='__main__':main()
